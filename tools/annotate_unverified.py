#!/usr/bin/env python3
"""Generate annotated copies of files containing monetary claims.

Reads a matches JSON file (default `reports/balance_matches.json`) with entries
that reference repo files and amount snippets. For each file that has matches,
writes an annotated copy under the `unverified_annotations/` directory that
contains a short header listing matches and a recommended `UNVERIFIED` note.

This script is conservative and does not modify original files.
"""
import json
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]


def load_matches(path: Path):
    if not path.exists():
        print(f"Matches file not found: {path}")
        return []
    try:
        return json.loads(path.read_text())
    except Exception as e:
        print("Failed to read matches JSON:", e)
        return []


def group_by_file(matches):
    files = {}
    for m in matches:
        # tolerant field names
        file_path = m.get('file') or m.get('path') or m.get('filePath') or m.get('filename')
        snippet = m.get('match') or m.get('snippet') or m.get('amount') or ''
        if not file_path:
            continue
        files.setdefault(file_path, []).append(snippet)
    return files


def make_annotation_header(relpath, snippets):
    header = []
    header.append("<!-- UNVERIFIED ANNOTATIONS - autogenerated by tools/annotate_unverified.py -->")
    header.append(f"<!-- File: {relpath} -->")
    header.append("<!-- Detected monetary claims: -->")
    for s in snippets:
        header.append(f"<!--  - {s} -->")
    header.append("<!-- Recommended tag: [UNVERIFIED] - verify via Pesapal/bank/accounting APIs and update accordingly -->\n")
    return '\n'.join(header) + '\n'


def write_annotated_copy(root: Path, relpath: str, snippets, outroot: Path):
    src = root / relpath
    dest = outroot / relpath
    dest.parent.mkdir(parents=True, exist_ok=True)
    header = make_annotation_header(relpath, snippets)
    if not src.exists():
        # create a small file listing snippets
        dest.write_text(header + f"<!-- Original file not found in repo at {src} -->\n")
        return
    content = src.read_text()
    # Write annotated file with header at top
    dest.write_text(header + content)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--matches', default=str(ROOT / 'reports' / 'balance_matches.json'))
    p.add_argument('--out', default=str(ROOT / 'unverified_annotations'))
    args = p.parse_args()

    matches = load_matches(Path(args.matches))
    grouped = group_by_file(matches)
    outroot = Path(args.out)
    outroot.mkdir(parents=True, exist_ok=True)

    if not grouped:
        print('No matches found or unable to parse matches file.')
        sys.exit(0)

    for relpath, snippets in grouped.items():
        write_annotated_copy(ROOT, relpath, snippets, outroot)

    print('Annotated copies written to', outroot)


if __name__ == '__main__':
    main()
