#!/usr/bin/env python3
"""Regenerate the ALLMDFILESREFS.md inventory from all markdown files."""

import logging
from pathlib import Path

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
REF_FILE = ROOT / 'ALLMDFILESREFS.md'


def scan_markdown_files() -> list[Path]:
    return [p for p in sorted(ROOT.rglob('*.md')) if p.is_file()]


def regenerate_refs() -> None:
    md_files = scan_markdown_files()
    header = [
        '# All Markdown Files Reference\n',
        f'**Last Updated:** {Path().resolve().as_posix()}\n',
        f'**Total Files:** {len(md_files)}\n\n',
        '## Markdown Files Index\n\n'
    ]
    header.extend(f'./{path.relative_to(ROOT).as_posix()}\n' for path in md_files)

    REF_FILE.write_text(''.join(header), encoding='utf-8')
    logger.info(f'ALLMDFILESREFS.md regenerated with {len(md_files)} markdown files')


