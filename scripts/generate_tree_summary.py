def should_ignore(path: Path, relative_path: str) -> bool:
    """Check if path should be ignored"""
    for part in path.parts:
        for pattern in IGNORE_PATTERNS:
            if pattern.startswith('.'):
                if part == pattern:
                    return True
            elif '*' in pattern:
                import fnmatch
                if fnmatch.fnmatch(part, pattern):
                    return True
    return False

